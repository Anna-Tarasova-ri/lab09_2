#pragma once

#include <iostream>

#define Z 5                        // значення z – за ним препроцесор обирає гілку

#define SQR(a)     ((a)*(a))                        // піднесення до квадрата
#define MAX(a, b)  (((a) > (b)) ? (a) : (b))        // максимум з двох чисел
#define MIN(a, b)  (((a) < (b)) ? (a) : (b))        // мінімум з двох чисел
#define ABS(a)     (((a) < 0) ? -(a) : (a))         // модуль числа

// виведення повідомлення та значення дійсного числа
// символ '\' – продовження макроса, оператор '#' – перетворення аргумента у рядок
#define PRINTR(w) \
    do { \
        std::cout << "result :" << std::endl; \
        std::cout << #w << " = " << (w) << std::endl; \
    } while (0)

// виведення значення змінної (контрольне виведення)
#define PRINTV(v) \
    do { \
        std::cout << "control output" << std::endl; \
        std::cout << #v << " = " << (v) << std::endl; \
    } while (0)